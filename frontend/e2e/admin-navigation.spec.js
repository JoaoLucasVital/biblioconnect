import {test,expect} from '@playwright/test';
import {loginUi} from './helpers.js';
import {captureReview} from './capture-review.js';

test('sidebar agrupada navega, recolhe, reabre e mantém menu mobile acessível',async({page})=>{
  await loginUi(page,{email:'admin@biblioconnect.com',senha:'admin123'});
  await page.goto('/admin/financeiro');
  const nav=page.locator('.bc-admin-rail').getByRole('navigation',{name:'Administração'});
  await expect(nav.getByRole('button',{name:'Gestão',exact:true})).toHaveAttribute('aria-expanded','true');
  await expect(nav.getByRole('link',{name:'Financeiro',exact:true})).toHaveAttribute('aria-current','page');
  await expect(nav.getByRole('link',{name:'Pedidos',exact:true})).toHaveCount(0);
  await captureReview(page,'sidebar-expandida');
  await nav.getByRole('button',{name:'Recolher menu'}).click();
  await expect(nav.getByRole('button',{name:'Expandir menu'})).toBeVisible();
  await expect.poll(()=>nav.evaluate(node=>node.getBoundingClientRect().width)).toBeLessThan(90);
  const acervo=nav.getByRole('button',{name:'Acervo',exact:true});
  await page.keyboard.press('Tab');await page.keyboard.press('Tab');await expect(acervo).toBeFocused();
  await expect(acervo.locator('.bc-admin-tooltip')).toBeVisible();
  await captureReview(page,'sidebar-compacta');
  await acervo.click();
  await expect(nav.getByRole('link',{name:'Avaliações',exact:true})).toBeVisible();
  await nav.getByRole('link',{name:'Avaliações',exact:true}).click();await expect(page).toHaveURL(/\/admin\/avaliacoes$/);
  await expect(page.getByRole('heading',{name:'Vozes do acervo.',level:1})).toBeVisible();
  const operations=nav.getByRole('button',{name:'Operações',exact:true});
  await operations.focus();await operations.press('Space');await expect(nav.getByRole('link',{name:'Entregas',exact:true})).toBeVisible();
  await operations.press('Space');await expect(nav.getByRole('link',{name:'Entregas',exact:true})).toHaveCount(0);
  for(let index=0;index<4;index++)await nav.getByRole('button',{name:index%2?'Expandir menu':'Recolher menu'}).click();
  await expect(nav.getByRole('button',{name:'Recolher menu'})).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.setViewportSize({width:360,height:800});
  const trigger=page.getByRole('button',{name:'Menu administrativo'});await trigger.click();
  const dialog=page.getByRole('dialog',{name:'Administração'});
  await expect(dialog).toBeVisible();await dialog.getByRole('button',{name:'Operações',exact:true}).click();
  await expect.poll(()=>dialog.locator('.bc-admin-group-region[aria-hidden=true]').evaluateAll(nodes=>nodes.every(node=>node.clientHeight===0))).toBe(true);
  await expect(dialog.getByRole('button',{name:'Fechar diálogo'})).toBeInViewport();
  await captureReview(page,'sidebar-mobile');
  await dialog.getByRole('link',{name:'Entregas',exact:true}).click();await expect(page).toHaveURL(/\/admin\/entregas$/);
  await expect(dialog).toHaveCount(0);await expect(trigger).toBeFocused();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.emulateMedia({reducedMotion:'reduce'});await page.setViewportSize({width:1440,height:1000});
  await nav.getByRole('button',{name:'Recolher menu'}).click();
  await expect(nav.getByRole('button',{name:'Expandir menu'})).toBeVisible();
  expect(await page.locator('.bc-admin-content').evaluate(node=>getComputedStyle(node).transform)).toBe('none');
});
