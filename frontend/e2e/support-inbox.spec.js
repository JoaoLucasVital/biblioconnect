import {test,expect} from '@playwright/test';
import {authHeaders,createConfirmedClient,loginUi,sessionCredentials} from './helpers.js';
import {captureReview} from './capture-review.js';
test('caixa de entrada responde, atualiza, encerra e funciona em tela pequena',async({page,request})=>{
  test.setTimeout(60000);
  const credentials={email:'admin@biblioconnect.com',senha:'admin123'};
  const admin=await sessionCredentials(await request.post(`${process.env.QA_API_URL}/login`,{headers:{Origin:process.env.QA_BASE_URL},data:credentials}));
  const client=await createConfirmedClient({request,nome:'Marina de Albuquerque'}),other=await createConfirmedClient({request,nome:'Pedro Nascimento'});
  const send=async(user,texto)=>expect((await request.post(`${process.env.QA_API_URL}/chat/mensagens`,{headers:authHeaders(user.token),data:{texto}})).ok()).toBe(true);
  await send(client,'Olá! Gostaria de confirmar o horário de retirada.');await send(client,'Meu pedido é para esta semana. Posso buscar amanhã?');
  await send(other,'O livro já chegou. Obrigado pelo atendimento!');
  const conversations=await(await request.get(`${process.env.QA_API_URL}/admin/chat/conversas`,{headers:authHeaders(admin)})).json();
  const id=conversations.find(item=>item.usuario.id===client.usuario.id).id,closedId=conversations.find(item=>item.usuario.id===other.usuario.id).id;
  expect((await request.patch(`${process.env.QA_API_URL}/admin/chat/conversas/${closedId}/status`,{headers:authHeaders(admin),data:{status:'encerrada'}})).ok()).toBe(true);
  await loginUi(page,credentials);await page.goto('/admin/chat');
  await expect(page.getByRole('heading',{name:'Atendimentos.',level:1})).toBeVisible();
  await expect(page.getByRole('button',{name:/Marina de Albuquerque/})).toBeVisible();
  await page.getByRole('switch',{name:'Tema escuro'}).check();
  await captureReview(page,'atendimento-caixa-entrada');
  await page.getByRole('searchbox',{name:'Buscar conversas'}).fill('Marina');
  await expect(page.getByRole('button',{name:/Pedro Nascimento/})).toHaveCount(0);
  await page.getByRole('searchbox',{name:'Buscar conversas'}).clear();
  await page.getByRole('button',{name:/Encerradas/}).click();await page.getByRole('button',{name:/Pedro Nascimento/}).click();
  await expect(page.getByText('Esta conversa foi encerrada. O histórico continua disponível.')).toBeVisible();
  await expect(page.getByLabel('Resposta ao cliente')).toHaveCount(0);
  await page.getByRole('button',{name:/Abertas/}).click();await page.getByRole('button',{name:/Marina de Albuquerque/}).click();
  const log=page.getByRole('log',{name:'Mensagens da conversa'});
  await expect(log.getByText('Olá! Gostaria de confirmar o horário de retirada.')).toBeVisible();
  await page.getByLabel('Resposta ao cliente').fill('Olá, Marina! Seu livro estará disponível amanhã na biblioteca.');
  await page.getByRole('button',{name:'Responder',exact:true}).click();
  await expect(log.getByText('Olá, Marina! Seu livro estará disponível amanhã na biblioteca.')).toBeVisible();
  await expect.poll(async()=>(await(await request.get(`${process.env.QA_API_URL}/chat`,{headers:authHeaders(client.token)})).json()).mensagens.some(message=>message.texto.includes('Seu livro estará disponível'))).toBe(true);
  await send(client,'Perfeito, muito obrigada!');
  await expect(log.getByText('Perfeito, muito obrigada!')).toBeVisible({timeout:12000});
  await captureReview(page,'atendimento-conversa-desktop');
  for(const width of [1100,1024,768,360]){
    await page.setViewportSize({width,height:800});
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true);
    await expect(page.getByLabel('Resposta ao cliente')).toBeVisible();
  }
  await expect(page.getByRole('button',{name:'Voltar à lista'})).toBeVisible();
  await expect.poll(()=>log.evaluate(node=>node.scrollHeight-node.scrollTop-node.clientHeight)).toBeLessThan(3);
  expect(await page.getByRole('region',{name:'Conversa com Marina de Albuquerque'}).locator('.bc-inbox-thread-header').evaluate(node=>node.getBoundingClientRect().height)).toBeLessThan(170);
  await captureReview(page,'atendimento-conversa-mobile');
  await page.getByRole('button',{name:'Voltar à lista'}).click();
  await expect(page.getByRole('button',{name:/Marina de Albuquerque/})).toBeFocused();
  await page.getByRole('button',{name:/Marina de Albuquerque/}).click();
  await expect(page.getByRole('log',{name:'Mensagens da conversa'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Voltar à lista'})).toBeFocused();
  await page.getByRole('button',{name:'Encerrar',exact:true}).click();
  await expect(page.getByText('Esta conversa foi encerrada. O histórico continua disponível.')).toBeVisible();
  await expect.poll(async()=>(await(await request.get(`${process.env.QA_API_URL}/admin/chat/conversas/${id}`,{headers:authHeaders(admin)})).json()).status).toBe('encerrada');
});
